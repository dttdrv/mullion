#include "d3d9_state.hpp"
#include <bit>

namespace mullion {

static DWORD
FloatBits(float f) {
  return std::bit_cast<DWORD>(f);
}

void
D3D9InitRenderStates(std::array<DWORD, 256> &rs, bool AutoDepthStencil) {
  rs.fill(0);

  rs[D3DRS_ZENABLE] = AutoDepthStencil ? D3DZB_TRUE : D3DZB_FALSE;
  rs[D3DRS_FILLMODE] = D3DFILL_SOLID;
  rs[D3DRS_SHADEMODE] = D3DSHADE_GOURAUD;
  rs[D3DRS_ZWRITEENABLE] = TRUE;
  rs[D3DRS_ALPHATESTENABLE] = FALSE;
  rs[D3DRS_LASTPIXEL] = TRUE;
  rs[D3DRS_SRCBLEND] = D3DBLEND_ONE;
  rs[D3DRS_DESTBLEND] = D3DBLEND_ZERO;
  rs[D3DRS_CULLMODE] = D3DCULL_CCW;
  rs[D3DRS_ZFUNC] = D3DCMP_LESSEQUAL;
  rs[D3DRS_ALPHAREF] = 0;
  rs[D3DRS_ALPHAFUNC] = D3DCMP_ALWAYS;
  rs[D3DRS_DITHERENABLE] = FALSE;
  rs[D3DRS_ALPHABLENDENABLE] = FALSE;
  rs[D3DRS_FOGENABLE] = FALSE;
  rs[D3DRS_SPECULARENABLE] = FALSE;
  rs[D3DRS_FOGCOLOR] = 0;
  rs[D3DRS_FOGTABLEMODE] = D3DFOG_NONE;
  rs[D3DRS_FOGSTART] = FloatBits(0.0f);
  rs[D3DRS_FOGEND] = FloatBits(1.0f);
  rs[D3DRS_FOGDENSITY] = FloatBits(1.0f);
  rs[D3DRS_RANGEFOGENABLE] = FALSE;
  rs[D3DRS_STENCILENABLE] = FALSE;
  rs[D3DRS_STENCILFAIL] = D3DSTENCILOP_KEEP;
  rs[D3DRS_STENCILZFAIL] = D3DSTENCILOP_KEEP;
  rs[D3DRS_STENCILPASS] = D3DSTENCILOP_KEEP;
  rs[D3DRS_STENCILFUNC] = D3DCMP_ALWAYS;
  rs[D3DRS_STENCILREF] = 0;
  rs[D3DRS_STENCILMASK] = 0xFFFFFFFF;
  rs[D3DRS_STENCILWRITEMASK] = 0xFFFFFFFF;
  rs[D3DRS_TEXTUREFACTOR] = 0xFFFFFFFF;
  rs[D3DRS_CLIPPING] = TRUE;
  rs[D3DRS_LIGHTING] = TRUE;
  rs[D3DRS_AMBIENT] = 0;
  rs[D3DRS_FOGVERTEXMODE] = D3DFOG_NONE;
  rs[D3DRS_COLORVERTEX] = TRUE;
  rs[D3DRS_LOCALVIEWER] = TRUE;
  rs[D3DRS_NORMALIZENORMALS] = FALSE;
  rs[D3DRS_DIFFUSEMATERIALSOURCE] = D3DMCS_COLOR1;
  rs[D3DRS_SPECULARMATERIALSOURCE] = D3DMCS_COLOR2;
  rs[D3DRS_AMBIENTMATERIALSOURCE] = D3DMCS_MATERIAL;
  rs[D3DRS_EMISSIVEMATERIALSOURCE] = D3DMCS_MATERIAL;
  rs[D3DRS_VERTEXBLEND] = D3DVBF_DISABLE;
  rs[D3DRS_CLIPPLANEENABLE] = 0;
  rs[D3DRS_POINTSIZE] = FloatBits(1.0f);
  rs[D3DRS_POINTSIZE_MIN] = FloatBits(1.0f);
  rs[D3DRS_POINTSPRITEENABLE] = FALSE;
  rs[D3DRS_POINTSCALEENABLE] = FALSE;
  rs[D3DRS_POINTSCALE_A] = FloatBits(1.0f);
  rs[D3DRS_POINTSCALE_B] = FloatBits(0.0f);
  rs[D3DRS_POINTSCALE_C] = FloatBits(0.0f);
  rs[D3DRS_MULTISAMPLEANTIALIAS] = TRUE;
  rs[D3DRS_MULTISAMPLEMASK] = 0xFFFFFFFF;
  rs[D3DRS_PATCHEDGESTYLE] = D3DPATCHEDGE_DISCRETE;
  rs[D3DRS_DEBUGMONITORTOKEN] = D3DDMT_ENABLE;
  // the default is the caps' MaxPointSize
  rs[D3DRS_POINTSIZE_MAX] = FloatBits(256.0f);
  rs[D3DRS_INDEXEDVERTEXBLENDENABLE] = FALSE;
  rs[D3DRS_COLORWRITEENABLE] = 0xF;
  rs[D3DRS_TWEENFACTOR] = FloatBits(0.0f);
  rs[D3DRS_BLENDOP] = D3DBLENDOP_ADD;
  rs[D3DRS_POSITIONDEGREE] = D3DDEGREE_CUBIC;
  rs[D3DRS_NORMALDEGREE] = D3DDEGREE_LINEAR;
  rs[D3DRS_SCISSORTESTENABLE] = FALSE;
  rs[D3DRS_SLOPESCALEDEPTHBIAS] = FloatBits(0.0f);
  rs[D3DRS_ANTIALIASEDLINEENABLE] = FALSE;
  rs[D3DRS_MINTESSELLATIONLEVEL] = FloatBits(1.0f);
  rs[D3DRS_MAXTESSELLATIONLEVEL] = FloatBits(1.0f);
  rs[D3DRS_ADAPTIVETESS_X] = FloatBits(0.0f);
  rs[D3DRS_ADAPTIVETESS_Y] = FloatBits(0.0f);
  rs[D3DRS_ADAPTIVETESS_Z] = FloatBits(1.0f);
  rs[D3DRS_ADAPTIVETESS_W] = FloatBits(0.0f);
  rs[D3DRS_ENABLEADAPTIVETESSELLATION] = FALSE;
  rs[D3DRS_TWOSIDEDSTENCILMODE] = FALSE;
  rs[D3DRS_CCW_STENCILFAIL] = D3DSTENCILOP_KEEP;
  rs[D3DRS_CCW_STENCILZFAIL] = D3DSTENCILOP_KEEP;
  rs[D3DRS_CCW_STENCILPASS] = D3DSTENCILOP_KEEP;
  rs[D3DRS_CCW_STENCILFUNC] = D3DCMP_ALWAYS;
  rs[D3DRS_COLORWRITEENABLE1] = 0xF;
  rs[D3DRS_COLORWRITEENABLE2] = 0xF;
  rs[D3DRS_COLORWRITEENABLE3] = 0xF;
  rs[D3DRS_BLENDFACTOR] = 0xFFFFFFFF;
  rs[D3DRS_SRGBWRITEENABLE] = FALSE;
  rs[D3DRS_DEPTHBIAS] = FloatBits(0.0f);
  rs[D3DRS_SEPARATEALPHABLENDENABLE] = FALSE;
  rs[D3DRS_SRCBLENDALPHA] = D3DBLEND_ONE;
  rs[D3DRS_DESTBLENDALPHA] = D3DBLEND_ZERO;
  rs[D3DRS_BLENDOPALPHA] = D3DBLENDOP_ADD;
}

void
D3D9InitTextureStageStates(std::array<std::array<DWORD, D3DTSS_CONSTANT + 1>, 8> &States) {
  for (DWORD i = 0; i < States.size(); i++) {
    auto &s = States[i];
    s.fill(0);
    s[D3DTSS_COLOROP] = i == 0 ? D3DTOP_MODULATE : D3DTOP_DISABLE;
    s[D3DTSS_COLORARG1] = D3DTA_TEXTURE;
    s[D3DTSS_COLORARG2] = D3DTA_CURRENT;
    s[D3DTSS_ALPHAOP] = i == 0 ? D3DTOP_SELECTARG1 : D3DTOP_DISABLE;
    s[D3DTSS_ALPHAARG1] = D3DTA_TEXTURE;
    s[D3DTSS_ALPHAARG2] = D3DTA_CURRENT;
    s[D3DTSS_TEXCOORDINDEX] = i;
    s[D3DTSS_TEXTURETRANSFORMFLAGS] = D3DTTFF_DISABLE;
    s[D3DTSS_COLORARG0] = D3DTA_CURRENT;
    s[D3DTSS_ALPHAARG0] = D3DTA_CURRENT;
    s[D3DTSS_RESULTARG] = D3DTA_CURRENT;
  }
}

} // namespace mullion
