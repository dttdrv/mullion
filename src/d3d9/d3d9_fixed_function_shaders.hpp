// the shaders the fixed-function draw path emits for the one vertex format this milestone has. they are Direct3D 9's
// fixed-function transform expressed in the shader model the D3D11 core takes: a vertex already in screen space is
// mapped onto the viewport (D3D9's XYZRHW, whose w is 1/rhw), and the vertex's colour goes to the target unchanged.
//
// compiled once, offline, from the sources below with Wine's d3dcompiler_47 (as tests/d3d11's tests use it) at
// vs_5_0 and ps_5_0, and carried here as the bytes D3D11CreateVertexShader/D3D11CreatePixelShader take. to regenerate,
// compile these two sources with D3DCompile and write the blobs out as the arrays below (the milestone's tests do not
// compile shaders at runtime: a game's shaders are the only DXBC this library translates, and these are its own).
//
// the pixel shader declares the position it does not read so that its colour input is register 1, where the vertex
// shader writes it: this core's pipeline binds the two shaders by their registers, not by semantic name.
//
// vertex:
//   cbuffer Viewport : register(b0) {
//     float2 viewport_size;
//     float2 padding;
//   };
//   struct VSInput {
//     float4 position : POSITION;   // xy in screen pixels, z, and 1/rhw
//     float4 colour : COLOR0;       // D3DCOLOR, read as BGRA8
//   };
//   struct VSOutput {
//     float4 position : SV_POSITION;
//     float4 colour : COLOR0;
//   };
//   VSOutput main(VSInput input) {
//     VSOutput output;
//     output.position = float4(input.position.x * 2.0 / viewport_size.x - 1.0,
//                              1.0 - input.position.y * 2.0 / viewport_size.y,
//                              input.position.z, input.position.w);
//     output.colour = input.colour;
//     return output;
//   }
//
// pixel:
//   struct PSInput {
//     float4 position : SV_POSITION;
//     float4 colour : COLOR0;
//   };
//   float4 main(PSInput input) : SV_TARGET { return input.colour; }
