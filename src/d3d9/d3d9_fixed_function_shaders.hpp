// the shaders the fixed-function draw path emits for the vertex formats this milestone transforms. they are Direct3D 9's
// fixed-function transform expressed in the shader model the D3D11 core takes: a vertex already in screen space is
// mapped through the viewport (D3D9's XYZRHW, whose w is 1/rhw), and the vertex's colour goes to the target unchanged.
//
// compiled once, offline, from the sources below at vs_5_0 and ps_5_0, and carried here as the bytes
// D3D11CreateVertexShader/D3D11CreatePixelShader take. the compiler is Microsoft's HLSL compiler -- the
// d3dcompiler_47.dll the Wine prefix's own applications load, which stamps itself "Microsoft (R) HLSL Shader Compiler
// 10.1", and the one tests/d3d11's shaders are compiled by. to regenerate, compile these sources with D3DCompile and
// write the blobs out as the arrays below (this library does not compile shaders at runtime: a game's shaders are the
// only DXBC it translates, and these are its own).
//
// the pixel shader declares the position it does not read so that its colour input is register 1, where the vertex
// shader writes it: this core's pipeline binds the two shaders by their registers, not by semantic name.
//
// vertex:
//   cbuffer Viewport : register(b0) {
//     float4 viewport;              // x, y, width, height
//   };
//   struct VSInput {
//     float4 position : POSITION;   // xy in screen pixels, z, and 1/rhw
//     float4 colour : COLOR0;       // D3DCOLOR, read as BGRA8
//   };
//   struct VSOutput {
//     float4 position : SV_POSITION;
//     float4 colour : COLOR0;
//   };
//   VSOutput main(VSInput input) {
//     VSOutput output;
//     float w = 1.0 / input.position.w;   // D3D9's screen-space vertex carries rhw, the reciprocal of its w
//     output.position = float4(((input.position.x - viewport.x) * 2.0 / viewport.z - 1.0) * w,
//                              (1.0 - (input.position.y - viewport.y) * 2.0 / viewport.w) * w,
//                              input.position.z * w, w);
//     output.colour = input.colour;
//     return output;
//   }
//
// pixel, GOURAUD (the vertex colour interpolated over the triangle):
//   struct PSInput {
//     float4 position : SV_POSITION;
//     float4 colour : COLOR0;
//   };
//   float4 main(PSInput input) : SV_TARGET { return input.colour; }
//
// pixel, FLAT (one vertex's colour for the whole triangle: D3D9's flat shading takes the first vertex of the
// primitive, which is the provoking vertex D3D11's nointerpolation reads). the modifier is on a parameter rather than
// on a struct member, which is the one spelling of it that no compiler's reading of a struct member can quietly turn
// into an interpolated input -- which would make FLAT a quieter GOURAUD:
//   float4 main(float4 position : SV_POSITION, nointerpolation float4 colour : COLOR0) : SV_TARGET {
//     return colour;
//   }
// a textured draw's shaders (milestone 4): the same screen-space vertex with the stage's texture coordinates, and a
// pixel shader that samples the texture and applies Direct3D 9's stage-0 colour and alpha operations to the arguments
// they name. D3D9 lets an application compose that operation out of ops and arguments no fixed set of shaders can
// carry, so the operation and its arguments are constants the device writes before every draw, out of its texture
// stage state:
//   cbuffer Stage : register(b0) {
//     uint4 ops;     // x colour op, y colour arg1, z colour arg2, w alpha op
//     uint4 args;    // x alpha arg1, y alpha arg2
//     float4 factor; // D3DRS_TEXTUREFACTOR
//   };
//   Texture2D texture0 : register(t0);
//   SamplerState sampler0 : register(s0);
//   float4 argument(uint which, float4 sampled, float4 colour) {
//     if (which == 0) return sampled;                 // D3DTA_TEXTURE
//     if (which == 1) return colour;                  // D3DTA_DIFFUSE (D3DTA_CURRENT at stage 0)
//     return factor;                                  // D3DTA_TFACTOR
//   }
//   float4 blend(uint op, float4 first, float4 second, float4 current) {
//     if (op == 1) return first;                      // SELECTARG1
//     if (op == 2) return second;                     // SELECTARG2
//     if (op == 3) return first * second;             // MODULATE
//     if (op == 4) return first + second;             // ADD
//     if (op == 5) return first - second;             // SUBTRACT
//     return current;                                 // DISABLE, which passes stage 0 the vertex colour
//   }
// vertex, textured (the format milestone 4 adds the stage's texture coordinates to):
//   struct VSInput {
//     float4 position : POSITION;
//     float4 colour : COLOR0;
//     float2 uv : TEXCOORD0;
//   };
//   struct VSOutput {
//     float4 position : SV_POSITION;
//     float4 colour : COLOR0;
//     float2 uv : TEXCOORD0;
//   };
//   VSOutput main(VSInput input) {
//     VSOutput output;
//     float w = 1.0 / input.position.w;
//     output.position = float4(((input.position.x - viewport.x) * 2.0 / viewport.z - 1.0) * w,
//                              (1.0 - (input.position.y - viewport.y) * 2.0 / viewport.w) * w,
//                              input.position.z * w, w);
//     output.colour = input.colour;
//     output.uv = input.uv;
//     return output;
//   }
// pixel, GOURAUD, textured:
//   struct PSInput {
//     float4 position : SV_POSITION;
//     float4 colour : COLOR0;
//     float2 uv : TEXCOORD0;
//   };
//   float4 main(PSInput input) : SV_TARGET {
//     float4 sampled = texture0.Sample(sampler0, input.uv);
//     float4 rgb = blend(ops.x, argument(ops.y, sampled, input.colour), argument(ops.z, sampled, input.colour),
//                        input.colour);
//     float4 alpha = blend(ops.w, argument(args.x, sampled, input.colour), argument(args.y, sampled, input.colour),
//                          input.colour);
//     return float4(rgb.rgb, alpha.a);
//   }
// pixel, FLAT, textured (as above, with the same nointerpolation parameter the untextured flat shader carries):
//   float4 main(float4 position : SV_POSITION, nointerpolation float4 colour : COLOR0,
//               float2 uv : TEXCOORD0) : SV_TARGET {
//     ...
//   }
