// the operation texture stage 0 performs: D3D9's colour and alpha operations and the arguments they take, as the
// constants the textured pixel shader reads (d3d9_fixed_function_shaders.hpp). the operations this build honours are
// the ones a fixed-function frame needs; every other operation, argument and modifier is refused rather than drawn as
// a different one.
class TextureStageState9 {
public:
  TextureStageState9() = default;
  // stage 0 defaults to MODULATE/SELECTARG1; later stages default to DISABLE for both colour and alpha. The
  // texcoord index defaults to the stage number (Wine device.c test_texture_stage_states)
  explicit TextureStageState9(DWORD colour_op, DWORD texcoord_index = 0)
      : colour_op_(colour_op), alpha_op_(colour_op == D3DTOP_DISABLE ? D3DTOP_DISABLE : D3DTOP_SELECTARG1),
        texcoord_index_(texcoord_index) {}

  static bool supported(D3DTEXTURESTAGESTATETYPE type);
  static bool usable_value(D3DTEXTURESTAGESTATETYPE type, DWORD value);
  // every type the device takes, which is what a state block enumerates
  static const D3DTEXTURESTAGESTATETYPE *all_types(UINT &count);

  HRESULT set(D3DTEXTURESTAGESTATETYPE type, DWORD value);
  HRESULT get(D3DTEXTURESTAGESTATETYPE type, DWORD *value) const;

  // the shader constants the operations and arguments make: ops is colour op, colour arg1, colour arg2 and alpha op,
  // args is alpha arg1 and alpha arg2. `current_as_previous` encodes D3DTA_CURRENT as 3 so a later stage reads the
  // previous stage's result rather than the vertex colour
  void constants(UINT32 ops[4], UINT32 args[4], bool current_as_previous = false) const;
  // the eight-stage combiner's board row for this stage, all raw D3D9 values (d3d9_device_draw.cpp fills the
  // StageBoard8 from these): ops is colour op, colour arg1, colour arg2 and alpha op; args is alpha arg1, alpha
  // arg2, the result arg and the D3DTSS_TEXTURETRANSFORMFLAGS, all raw; args0 is colour arg0, alpha arg0 and the
  // coordinate pass-through index (0xffffffff marks a stage whose generation flags this build does not generate for)
  void eight_board(UINT32 ops[4], UINT32 args[4], UINT32 args0[4]) const;
  // the bump-environment matrix, luminance scale and luminance offset the stage's D3DTSS_BUMPENV* states carry, as
  // the floats those DWORDs hold
  void bump_env(float matrix[4], float &lscale, float &loffset) const;
  DWORD colour_op() const {
    return colour_op_;
  }
  DWORD colour_arg1() const {
    return colour_arg1_;
  }
  DWORD colour_arg2() const {
    return colour_arg2_;
  }
  DWORD alpha_op() const {
    return alpha_op_;
  }
  DWORD alpha_arg1() const {
    return alpha_arg1_;
  }
  DWORD alpha_arg2() const {
    return alpha_arg2_;
  }
  DWORD colour_arg0() const {
    return colour_arg0_;
  }
  DWORD alpha_arg0() const {
    return alpha_arg0_;
  }
  DWORD result_arg() const {
    return result_arg_;
  }
  DWORD constant_value() const {
    return constant_;
  }
  DWORD texcoord_index() const {
    return texcoord_index_;
  }
  DWORD texture_transform_flags() const {
    return texture_transform_flags_;
  }
  // whether this stage is skipped while no texture is bound: "when a texture stage has D3DTSS_COLORARG1 equal to
  // D3DTA_TEXTURE and the texture pointer for the stage is NULL, this stage and all stages after it are not processed"
  // (Microsoft Learn, Texture Blending), which for stage 0 is the vertex colour the frame already carries
  bool skipped_without_texture() const {
    return colour_arg1_ == D3DTA_TEXTURE;
  }

private:
  // what D3D9's device starts with for stage 0 (its documented defaults: MODULATE of the texture and the current
  // colour, and the texture's own alpha). a later stage starts DISABLE, which is D3D9's default past stage 0
  DWORD colour_op_ = D3DTOP_MODULATE;
  DWORD colour_arg1_ = D3DTA_TEXTURE;
  DWORD colour_arg2_ = D3DTA_CURRENT;
  DWORD alpha_op_ = D3DTOP_SELECTARG1;
  DWORD alpha_arg1_ = D3DTA_TEXTURE;
  DWORD alpha_arg2_ = D3DTA_CURRENT;
  DWORD colour_arg0_ = D3DTA_CURRENT;
  DWORD alpha_arg0_ = D3DTA_CURRENT;
  DWORD result_arg_ = D3DTA_CURRENT;
  DWORD constant_ = 0;
  DWORD bump_env_mat00_ = 0;
  DWORD bump_env_mat01_ = 0;
  DWORD bump_env_mat10_ = 0;
  DWORD bump_env_mat11_ = 0;
  DWORD bump_env_lscale_ = 0;
  DWORD bump_env_loffset_ = 0;
  DWORD texcoord_index_ = 0;
  DWORD texture_transform_flags_ = D3DTTFF_DISABLE;
};

